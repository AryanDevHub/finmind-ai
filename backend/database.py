load_dotenv()

# ───────────────────────────── Constants ─────────────────────────────────
EMBEDDING_DIM: Final[int] = 384                      # all-MiniLM-L6-v2
AGENT_DB_ROLE: Final[str] = "finmind_agent_ro"
AGENT_USER_SETTING: Final[str] = "app.current_user_id"
AGENT_VIEWS: Final[tuple[str, ...]] = ("agent_transactions", "agent_budgets")
AGENT_STATEMENT_TIMEOUT_MS: Final[int] = 3_000


# ───────────────────────────── Engine / sessions ─────────────────────────
def get_database_url() -> str:
    """Return the async DSN. Postgres only: pgvector and the agent sandbox require it."""
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError(
            "DATABASE_URL is not set. Example: "
            "postgresql+asyncpg://finmind:secret@localhost:5432/finmind"
        )
    for prefix in ("postgres://", "postgresql://"):
        if url.startswith(prefix):
            url = "postgresql+asyncpg://" + url[len(prefix):]
            break
    if not url.startswith("postgresql+asyncpg://"):
        raise RuntimeError("DATABASE_URL must be a PostgreSQL URL (driver: asyncpg).")
    return url


@lru_cache(maxsize=1)
def get_engine() -> AsyncEngine:
    return create_async_engine(
        get_database_url(),
        pool_size=int(os.getenv("DB_POOL_SIZE", "10")),
        max_overflow=int(os.getenv("DB_MAX_OVERFLOW", "10")),
        pool_pre_ping=True,
        pool_recycle=1800,
        connect_args={"timeout": 10, "command_timeout": 30},
    )


@lru_cache(maxsize=1)
def get_sessionmaker() -> async_sessionmaker[AsyncSession]:
    # expire_on_commit=False: ORM objects stay readable after commit without a lazy
    # reload (which would be an implicit await and raises under asyncio).
    return async_sessionmaker(get_engine(), expire_on_commit=False, autoflush=False)


def create_task_engine() -> AsyncEngine:
    """Per-task engine for Celery workers (NullPool: no cross-event-loop connection reuse)."""
    return create_async_engine(get_database_url(), poolclass=NullPool)


async def get_session() -> AsyncIterator[AsyncSession]:
    """FastAPI dependency. Callers commit explicitly; any exception rolls back."""
    async with get_sessionmaker()() as session:
        try:
            yield session
        except BaseException:
            await session.rollback()
            raise


@asynccontextmanager
async def session_scope() -> AsyncIterator[AsyncSession]:
    """Transactional scope for non-request code: commits on success, rolls back on error."""
    async with get_sessionmaker()() as session:
        try:
            yield session
            await session.commit()
        except BaseException:
            await session.rollback()
            raise


async def dispose_engine() -> None:
    """Call from the FastAPI lifespan shutdown hook."""
    if get_engine.cache_info().currsize:
        await get_engine().dispose()
        get_engine.cache_clear()
        get_sessionmaker.cache_clear()


async def ping() -> bool:
    async with get_engine().connect() as conn:
        return (await conn.execute(text("SELECT 1"))).scalar_one() == 1


# ───────────────────────────── Sandbox for the SQL agent ─────────────────
@asynccontextmanager
async def agent_readonly_session(user_id: uuid.UUID, tz: str | None = None) -> AsyncIterator[AsyncSession]:
    """
    Session for executing LLM-generated SQL. Defence in depth:
      1. READ ONLY transaction (writes fail at the engine level)
      2. SET LOCAL ROLE finmind_agent_ro: SELECT on the two agent views only,
         so base tables, users, refresh_tokens, pg_* catalogs of interest are denied
      3. Views filter rows with current_setting('app.current_user_id'), set here
         from the authenticated session and never from model output
      4. statement_timeout bounds runaway queries
    The transaction is always rolled back; nothing the agent runs can persist.
    """
    async with get_sessionmaker()() as session:
        trans = await session.begin()
        try:
            await session.execute(text("SET TRANSACTION READ ONLY"))
            await session.execute(
                text("SELECT set_config(:name, :value, true)"),
                {"name": AGENT_USER_SETTING, "value": str(user_id)},
            )
            if tz:  # date_trunc / ::date / now() then follow the user's calendar, not UTC
                await session.execute(text("SELECT set_config('TimeZone', :tz, true)"), {"tz": tz})
            await session.execute(text(f"SET LOCAL statement_timeout = {AGENT_STATEMENT_TIMEOUT_MS}"))
            await session.execute(text(f"SET LOCAL ROLE {AGENT_DB_ROLE}"))
            yield session
        finally:
            await trans.rollback()


# ───────────────────────────── ORM models ────────────────────────────────
class Base(DeclarativeBase):
    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(column_0_label)s",
            "uq": "uq_%(table_name)s_%(column_0_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "pk": "pk_%(table_name)s",
        }
    )


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    username: Mapped[str] = mapped_column(String(50), unique=True)
    email: Mapped[str] = mapped_column(String(320), unique=True)
    hashed_password: Mapped[str] = mapped_column(String(255))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, server_default=text("true"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class Transaction(Base):
    __tablename__ = "transactions"
    __table_args__ = (
        CheckConstraint("amount > 0", name="amount_positive"),
        CheckConstraint("transaction_type IN ('income', 'expense')", name="type_valid"),
        CheckConstraint("risk_level IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')", name="risk_level_valid"),
        Index("ix_transactions_user_occurred", "user_id", text("occurred_at DESC")),
        Index("ix_transactions_user_category_occurred", "user_id", "category", text("occurred_at DESC")),
        Index("ix_transactions_flagged", "user_id", "occurred_at", postgresql_where=text("is_flagged")),
        Index("ix_transactions_pending_embedding", "created_at", postgresql_where=text("embedding IS NULL")),
        Index(
            "ix_transactions_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_with={"m": 16, "ef_construction": 64},
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(Uuid, ForeignKey("users.id", ondelete="CASCADE"))
    description: Mapped[str] = mapped_column(String(200))
    merchant: Mapped[str | None] = mapped_column(String(120), nullable=True)
    amount: Mapped[Decimal] = mapped_column(Numeric(14, 2))
    category: Mapped[str] = mapped_column(String(32))
    transaction_type: Mapped[str] = mapped_column(String(16))
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    # Fraud scoring (written on the request path)
    fraud_score: Mapped[float] = mapped_column(Float, default=0.0, server_default=text("0"))
    risk_level: Mapped[str] = mapped_column(String(8), default="LOW", server_default="LOW")
    is_flagged: Mapped[bool] = mapped_column(Boolean, default=False, server_default=text("false"))
    fraud_factors: Mapped[list[dict[str, Any]] | None] = mapped_column(JSONB, nullable=True)
    model_version: Mapped[str | None] = mapped_column(String(32), nullable=True)

    # Nightly anomaly batch
    anomaly_score: Mapped[float | None] = mapped_column(Float, nullable=True)
    is_anomaly: Mapped[bool] = mapped_column(Boolean, default=False, server_default=text("false"))
    anomaly_method: Mapped[str | None] = mapped_column(String(24), nullable=True)  # isolation_forest | mad
    anomaly_scored_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    # Written asynchronously by the Celery worker
    embedding: Mapped[list[float] | None] = mapped_column(Vector(EMBEDDING_DIM), nullable=True)
    embedded_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)


class Budget(Base):
    __tablename__ = "budgets"
    __table_args__ = (
        UniqueConstraint("user_id", "category", "month", name="uq_budgets_user_category_month"),
        CheckConstraint("limit_amount > 0", name="limit_positive"),
        CheckConstraint("month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'", name="month_format"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(Uuid, ForeignKey("users.id", ondelete="CASCADE"), index=True)
    category: Mapped[str] = mapped_column(String(32))
    limit_amount: Mapped[Decimal] = mapped_column(Numeric(14, 2))
    spent_amount: Mapped[Decimal] = mapped_column(Numeric(14, 2), default=Decimal("0"), server_default=text("0"))
    month: Mapped[str] = mapped_column(String(7))  # 'YYYY-MM'


class RefreshToken(Base):
    """
    Rotating refresh tokens. Only a SHA-256 of the token is stored. Each
    refresh revokes the presented token and issues a new one in the same
    `family_id`. Presenting an already-revoked token signals theft/replay and
    the whole family is revoked.
    """

    __tablename__ = "refresh_tokens"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)  # jti
    user_id: Mapped[uuid.UUID] = mapped_column(Uuid, ForeignKey("users.id", ondelete="CASCADE"), index=True)
    family_id: Mapped[uuid.UUID] = mapped_column(Uuid, index=True)
    token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    issued_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    replaced_by: Mapped[uuid.UUID | None] = mapped_column(Uuid, nullable=True)


def spent_subquery(start: datetime, end: datetime):
    """Correlated scalar subquery: a budget row's live expense total in [start, end). Sargable on occurred_at."""
    return (
        select(func.coalesce(func.sum(Transaction.amount), 0))
        .where(
            Transaction.user_id == Budget.user_id,
            Transaction.category == Budget.category,
            Transaction.transaction_type == "expense",
            Transaction.occurred_at >= start,
            Transaction.occurred_at < end,
        )
        .scalar_subquery()
    )

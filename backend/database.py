"""
database.py — async persistence layer (SQLAlchemy 2.0 + asyncpg + pgvector).

Design notes
------------
* Fully async: no sync Session anywhere. FastAPI endpoints receive an
  `AsyncSession` via `get_session`; Celery tasks build a short-lived
  NullPool engine via `create_task_engine` (each task runs in its own event
  loop, so a shared connection pool must not be reused across them).
* Primary keys are UUIDv4 — no enumerable integer IDs leak through URLs.
* Embeddings live on the transactions row (`vector(384)`, HNSW cosine index);
  they are written by the Celery worker, NOT on the request path. A partial
  index on `embedding IS NULL` makes backfill cheap.
* Money is `NUMERIC(14, 2)`, never float.
* Schema changes go through Alembic only (no `create_all` in app code).
* The LLM Text-to-SQL agent never touches base tables. `agent_readonly_session`
  switches to a NOLOGIN role that can only SELECT from the user-scoped views
  `agent_transactions` / `agent_budgets` (created in the first migration),
  inside a READ ONLY transaction with a statement timeout. Row scoping is done
  by Postgres itself via the `app.current_user_id` setting, not by trusting
  SQL generated by the model.
"""

